using System.Collections.Immutable;
using System.Text;
using IronMapper.Generator.Analysis.Models;

namespace IronMapper.Generator.CodeGeneration;

/// <summary>
/// Converts a <see cref="MappingDescriptor"/> into a C# source file containing the mapping
/// extension methods inside <c>IronMapper.Generated.GeneratedMappers_{AssemblyName}</c>
/// (<see cref="GeneratedCodeOptions.ClassName"/>).
/// </summary>
/// <remarks>
/// For each mapping the emitter generates four methods:
/// <list type="bullet">
///   <item><c>MapToDestType(this SourceType source) → DestType</c> — creates a new instance.</item>
///   <item><c>MapToDestType(this SourceType source, DestType destination) → void</c> — in-place update (skips init-only properties).</item>
///   <item><c>MapToDestTypeList(this IEnumerable&lt;SourceType&gt;? source) → List&lt;DestType&gt;</c> — collection shorthand (no LINQ).</item>
///   <item><c>MapToDestTypeArray(this IEnumerable&lt;SourceType&gt;? source) → DestType[]</c> — collection shorthand.</item>
/// </list>
/// </remarks>
internal static class MapperCodeEmitter
{
    /// <summary>
    /// Private generic holder of cached converters, declared once in <c>GeneratedMappers.g.cs</c>
    /// (<see cref="EmitClassDeclaration"/>) and used by every mapping file of the assembly.
    /// </summary>
    public const string ConverterCacheName = "ConverterCache";

    /// <summary>
    /// Private interface of the element mappers (<see cref="ElementMapperName"/>), declared once in
    /// <c>GeneratedMappers.g.cs</c>; generated rather than in the runtime package, so it adds no public API.
    /// </summary>
    public const string ElementMapperInterface = "IElementMapper";

    /// <summary>Generic loop of every <c>MapToXList</c> (see <see cref="EmitElementLoops"/>); no <c>MapTo</c> prefix, so it never collides with a mapping method.</summary>
    public const string ListHelperName = "MapElementsToList";

    /// <summary>Generic loop of every <c>MapToXArray</c> (see <see cref="EmitElementLoops"/>).</summary>
    public const string ArrayHelperName = "MapElementsToArray";

    /// <summary>
    /// Generates the source text for a single mapping. The method name, the helper-name scope and the hint name
    /// come from <paramref name="entry"/> (see <see cref="Analysis.MappingPlanner"/>).
    /// </summary>
    /// <param name="descriptor">The mapping to emit.</param>
    /// <param name="entry">The plan entry of <paramref name="descriptor"/>.</param>
    /// <param name="plan">The whole plan, used to resolve the method names of collection element mappings.</param>
    /// <param name="options">APIs available in the user's compilation (null checks).</param>
    /// <param name="methods">The optional overloads to generate (assembly settings with the mapping's overrides).</param>
    /// <returns>The full C# text of the generated file; add it under <see cref="MappingPlanEntry.HintName"/>.</returns>
    public static string Emit(MappingDescriptor descriptor, MappingPlanEntry entry, MappingPlan plan, GeneratedCodeOptions options,
        GeneratedMethods methods)
    {
        var sourceFullName = descriptor.SourceFullName ?? GetFullTypeName(descriptor.SourceNamespace, descriptor.SourceTypeName);
        var destFullName   = descriptor.DestFullName   ?? GetFullTypeName(descriptor.DestNamespace,   descriptor.DestTypeName);
        // Never more accessible than the mapped types (CS0050/CS0051 otherwise).
        var accessibility  = descriptor.MethodAccessibility;
        // MapTo{Name}, or a qualified name when it collides (IM0013).
        var methodName     = entry.MethodName;

        // Scope hook and transformer method names to this mapping to avoid CS0111 conflicts
        // (simple names, or full names when another mapping has the same simple names).
        var scope = entry.HelperScope;
        var scopedTransformers = ScopeTransformers(descriptor.ValueTransformers.AsImmutableArray(), scope);

        var sb = new StringBuilder();
        sb.AppendLine("// <auto-generated/>");
        sb.AppendLine("#nullable enable");
        sb.AppendLine();
        sb.AppendLine("namespace IronMapper.Generated");
        sb.AppendLine("{");
        // No accessibility modifier: it is declared once for the whole assembly (EmitClassDeclaration).
        sb.AppendLine($"    static partial class {options.ClassName}");
        sb.AppendLine("    {");

        // ------------------------------------------------------------------
        // Method 1: MapToDestType(this SourceType source) → DestType
        // ------------------------------------------------------------------
        sb.AppendLine($"        /// <summary>Maps <see cref=\"{EscapeXml(sourceFullName)}\"/> to a new <see cref=\"{EscapeXml(destFullName)}\"/>.</summary>");
        sb.AppendLine($"        /// <param name=\"source\">The source <see cref=\"{EscapeXml(sourceFullName)}\"/> instance to map.</param>");
        sb.AppendLine($"        /// <returns>A new <see cref=\"{EscapeXml(destFullName)}\"/> populated from <paramref name=\"source\"/>.</returns>");
        sb.AppendLine($"        {accessibility} static {destFullName} {methodName}(this {sourceFullName} source)");
        sb.AppendLine("        {");
        sb.AppendLine($"            {options.NullCheck("source", "return default!;")}"); // safe: `default!` is part of the emitted C# text

        if (descriptor.WhenConditionBody is not null)
            sb.AppendLine($"            if (!({descriptor.WhenConditionBody})) return default!;"); // safe: `default!` is part of the emitted C# text, not a local operator

        var hasHooks = descriptor.BeforeMapLambdaBody is not null || descriptor.AfterMapLambdaBody is not null;
        var beforeMapMethodName = $"BeforeMap{scope}";
        var afterMapMethodName  = $"AfterMap{scope}";

        if (descriptor.WholeObjectConverterType is not null)
        {
            sb.AppendLine($"            return {ConverterInstance(descriptor.WholeObjectConverterType, descriptor.WholeObjectConverterIsCached)}.Convert(source);");
        }
        else if (descriptor.WholeObjectLambdaBody is not null)
        {
            sb.AppendLine($"            return {descriptor.WholeObjectLambdaBody};");
        }
        else if (hasHooks)
        {
            // Two-step pattern required when BeforeMap or AfterMap hooks are present.
            sb.AppendLine($"            var destination = new {destFullName}();");

            if (descriptor.BeforeMapLambdaBody is not null)
                sb.AppendLine($"            {beforeMapMethodName}(source, destination);");

            foreach (var prop in descriptor.PropertyMappings)
            {
                if (prop.IsIgnored || prop.IsInitOnly) continue;
                sb.AppendLine($"            destination.{prop.DestPropertyName} = {BuildRhs(prop, scopedTransformers, scope)};");
            }

            if (descriptor.AfterMapLambdaBody is not null)
                sb.AppendLine($"            {afterMapMethodName}(source, destination);");

            sb.AppendLine("            return destination;");
        }
        else
        {
            sb.AppendLine($"            return new {destFullName}");
            sb.AppendLine("            {");
            foreach (var prop in descriptor.PropertyMappings)
            {
                if (prop.IsIgnored) continue;
                sb.Append("                ");
                sb.AppendLine(BuildPropertyInitializer(prop, scopedTransformers, scope) + ",");
            }
            sb.AppendLine("            };");
        }

        sb.AppendLine("        }");

        // ------------------------------------------------------------------
        // Method 2: MapToDestType(this SourceType source, DestType destination) → void  [in-place]
        // ------------------------------------------------------------------
        // Turned off (IronMapperGenerateInPlace / GenerateInPlace = false): the same body as a private method that only
        // the IMapper registration calls, so IMapper.Map(source, destination) keeps working.
        sb.AppendLine();
        if (methods.InPlace)
        {
            sb.AppendLine($"        /// <summary>Maps <see cref=\"{EscapeXml(sourceFullName)}\"/> into an existing <see cref=\"{EscapeXml(destFullName)}\"/> instance.</summary>");
            sb.AppendLine($"        /// <param name=\"source\">The source <see cref=\"{EscapeXml(sourceFullName)}\"/> to read from.</param>");
            sb.AppendLine($"        /// <param name=\"destination\">The <see cref=\"{EscapeXml(destFullName)}\"/> instance to populate. Init-only properties are not updated.</param>");
            sb.AppendLine($"        {accessibility} static void {methodName}(this {sourceFullName} source, {destFullName} destination)");
        }
        else
        {
            sb.AppendLine($"        private static void {PrivateInPlaceName(scope)}({sourceFullName} source, {destFullName} destination)");
        }
        sb.AppendLine("        {");
        sb.AppendLine($"            {options.NullCheck("source", "return;")}");
        sb.AppendLine($"            {options.NullCheck("destination", "return;")}");
        foreach (var prop in descriptor.PropertyMappings)
        {
            if (prop.IsIgnored || prop.IsInitOnly) continue;
            sb.AppendLine($"            destination.{prop.DestPropertyName} = {BuildRhs(prop, scopedTransformers, scope)};");
        }
        sb.AppendLine("        }");

        // ------------------------------------------------------------------
        // Methods 3 and 4: MapToDestTypeList / MapToDestTypeArray(this IEnumerable<SourceType>? source)
        // ------------------------------------------------------------------
        // The loops are written once, in the generic MapElementsToList/MapElementsToArray of GeneratedMappers.g.cs
        // (EmitClassDeclaration): checks for T[], List<T>, ICollection<T> with the exact capacity. Each mapping passes a
        // private struct whose Map calls Method 1 directly (by simple name: a referenced assembly may expose the same
        // MapToDestType(this SourceType) in IronMapper.Generated, CS0121 otherwise). A struct type argument makes the
        // JIT and NativeAOT compile a separate instance of the generic method for each mapping, in which Map is a direct,
        // inlinable call: no delegate, no interface dispatch. The parameter stays IEnumerable<T>.
        // Either method can be turned off (IronMapperGenerateList/Array, GenerateList/Array = false); nothing else calls
        // them: nested collection properties call Method 1 per element, and IMapper's registry then loops itself.
        var list = $"global::System.Collections.Generic.List<{destFullName}>";
        var src = sourceFullName;
        var elementMapper = ElementMapperName(scope);
        var typeArguments = $"{src}, {destFullName}, {elementMapper}";
        if (methods.List)
        {
            sb.AppendLine();
            sb.AppendLine($"        /// <summary>Maps each element of <paramref name=\"source\"/> to <see cref=\"{EscapeXml(destFullName)}\"/> and returns a <see cref=\"global::System.Collections.Generic.List{{T}}\"/>.</summary>");
            sb.AppendLine($"        {accessibility} static {list} {methodName}List(this global::System.Collections.Generic.IEnumerable<{src}>? source)");
            sb.AppendLine($"            => {ListHelperName}<{typeArguments}>(source);");
        }

        if (methods.Array)
        {
            sb.AppendLine();
            sb.AppendLine($"        /// <summary>Maps each element of <paramref name=\"source\"/> to <see cref=\"{EscapeXml(destFullName)}\"/> and returns an array.</summary>");
            sb.AppendLine($"        {accessibility} static {destFullName}[] {methodName}Array(this global::System.Collections.Generic.IEnumerable<{src}>? source)");
            sb.AppendLine($"            => {ArrayHelperName}<{typeArguments}>(source);");
        }

        if (methods.List || methods.Array)
        {
            sb.AppendLine();
            sb.AppendLine($"        private readonly struct {elementMapper} : {ElementMapperInterface}<{src}, {destFullName}>");
            sb.AppendLine("        {");
            sb.AppendLine($"            public {destFullName} Map({src} source) => {methodName}(source);");
            sb.AppendLine("        }");
        }

        // ------------------------------------------------------------------
        // Private collection helpers of nested collection properties
        // ------------------------------------------------------------------
        foreach (var prop in descriptor.PropertyMappings)
        {
            if (!UsesCollectionHelper(prop)) continue;
            sb.AppendLine();
            EmitCollectionHelper(sb, prop, scope, plan);
        }

        // ------------------------------------------------------------------
        // Private hook helpers (only emitted when BeforeMap/AfterMap are set)
        // ------------------------------------------------------------------
        if (descriptor.BeforeMapLambdaBody is not null)
        {
            sb.AppendLine();
            sb.AppendLine($"        private static void {beforeMapMethodName}({sourceFullName} source, {destFullName} destination)");
            sb.AppendLine("        {");
            foreach (var line in descriptor.BeforeMapLambdaBody.Split('\n'))
                sb.AppendLine($"            {line.TrimEnd()}");
            sb.AppendLine("        }");
        }

        if (descriptor.AfterMapLambdaBody is not null)
        {
            sb.AppendLine();
            sb.AppendLine($"        private static void {afterMapMethodName}({sourceFullName} source, {destFullName} destination)");
            sb.AppendLine("        {");
            foreach (var line in descriptor.AfterMapLambdaBody.Split('\n'))
                sb.AppendLine($"            {line.TrimEnd()}");
            sb.AppendLine("        }");
        }

        foreach (var t in scopedTransformers)
        {
            var fqn = t.FullyQualifiedTypeName;
            sb.AppendLine();
            if (t.LambdaBody.TrimStart().StartsWith("{", System.StringComparison.Ordinal))
            {
                var trimmedBody = t.LambdaBody.Trim();
                var blockContent = trimmedBody.Substring(1, trimmedBody.Length - 2).Trim();
                sb.AppendLine($"        private static {fqn} {t.MethodName}({fqn} value)");
                sb.AppendLine("        {");
                foreach (var line in blockContent.Split('\n'))
                    sb.AppendLine($"            {line.TrimStart()}");
                sb.AppendLine("        }");
            }
            else
            {
                sb.AppendLine($"        private static {fqn} {t.MethodName}({fqn} value) => {t.LambdaBody};");
            }
        }

        sb.AppendLine("    }");
        sb.AppendLine("}");

        return sb.ToString();
    }

    /// <summary>
    /// Generates the single declaration of the generated class (<see cref="GeneratedCodeOptions.ClassName"/>) that carries its accessibility modifier.
    /// The per-mapping files declare the class without a modifier, so this part alone decides it.
    /// </summary>
    /// <param name="accessibility">
    /// <c>"public"</c> when at least one generated method is public, otherwise <c>"internal"</c>.
    /// An internal class is invisible to referencing assemblies (unless they see the internals).
    /// </param>
    /// <param name="usesConverterCache">A generated mapping uses a cached converter: the class declares
    /// <see cref="ConverterCacheName"/> once for all mapping files.</param>
    /// <param name="excludeFromCodeCoverage"><c>IronMapperExcludeFromCodeCoverage</c>: mark the class with
    /// <c>[ExcludeFromCodeCoverage]</c>.</param>
    /// <param name="usesList">A generated mapping has <c>MapToXList</c>: declare <see cref="ListHelperName"/>.</param>
    /// <param name="usesArray">A generated mapping has <c>MapToXArray</c>: declare <see cref="ArrayHelperName"/>.</param>
    /// <param name="options">When <c>ArgumentNullException.ThrowIfNull</c> is not available, the class also declares
    /// the throw helper used by the null checks of the generated methods.</param>
    /// <param name="generatedCodeAttribute"><c>IronMapperGeneratedCodeAttribute</c> (default <c>true</c>): mark the class
    /// with <c>[GeneratedCode]</c>.</param>
    /// <remarks>
    /// The attributes are declared here once and apply to every part of the partial class: the mapping files, the
    /// registration for <c>IMapper</c> and <see cref="ConverterCacheName"/> (a second copy on another part would be CS0579).
    /// </remarks>
    public static (string hintName, string source) EmitClassDeclaration(string accessibility, bool usesConverterCache,
        bool excludeFromCodeCoverage, bool usesList, bool usesArray, GeneratedCodeOptions options, bool generatedCodeAttribute = true)
    {
        var sb = new StringBuilder();
        sb.AppendLine("// <auto-generated/>");
        sb.AppendLine("#nullable enable");
        sb.AppendLine();
        sb.AppendLine("namespace IronMapper.Generated");
        sb.AppendLine("{");
        sb.AppendLine("    /// <summary>Mapping extension methods generated by IronMapper for this assembly.</summary>");
        if (generatedCodeAttribute && options.HasGeneratedCodeAttribute)
            sb.AppendLine($"    [global::System.CodeDom.Compiler.GeneratedCode(\"IronMapper\", \"{GeneratorVersion}\")]");
        if (excludeFromCodeCoverage && options.HasExcludeFromCodeCoverage)
            sb.AppendLine("    [global::System.Diagnostics.CodeAnalysis.ExcludeFromCodeCoverage]");
        sb.AppendLine($"    {accessibility} static partial class {options.ClassName}");
        sb.AppendLine("    {");
        if (!options.UseThrowIfNull)
        {
            // One throw site for every null check: the mapping methods stay small enough to be inlined.
            if (options.HasDoesNotReturn)
                sb.AppendLine("        [global::System.Diagnostics.CodeAnalysis.DoesNotReturn]");
            sb.AppendLine($"        private static void {GeneratedCodeOptions.ThrowHelperName}(string paramName)");
            sb.AppendLine("            => throw new global::System.ArgumentNullException(paramName);");
        }
        if (usesConverterCache)
        {
            // One instance per converter type for the whole assembly. Created on first use by the type initializer,
            // which the runtime runs once even when several threads race; only converters without state get here.
            if (!options.UseThrowIfNull) sb.AppendLine();
            sb.AppendLine("        /// <summary>The single instance of a converter without state, created on first use.</summary>");
            sb.AppendLine($"        private static class {ConverterCacheName}<TConverter> where TConverter : class, new()");
            sb.AppendLine("        {");
            sb.AppendLine("            public static readonly TConverter Instance = new TConverter();");
            sb.AppendLine("        }");
        }
        if (usesList || usesArray) EmitElementLoops(sb, usesList, usesArray, needsSeparator: !options.UseThrowIfNull || usesConverterCache);
        sb.AppendLine("    }");
        sb.AppendLine("}");

        // Per-mapping hint names always contain "_MapTo", so this one cannot collide with them.
        return ("GeneratedMappers.g.cs", sb.ToString());
    }

    /// <summary>
    /// The loops of every <c>MapToXList</c>/<c>MapToXArray</c> of the assembly, written once: generic over the element types
    /// and a struct <c>TMapper</c> that maps one element (one per mapping, <see cref="ElementMapperName"/>). For a struct
    /// type argument the runtime compiles a separate instance (no shared generic code), so <c>mapper.Map</c> is a direct
    /// call that the JIT can inline, as in the per-mapping loops of 1.2.0 PR 4. Fast paths and capacities are the same:
    /// <c>T[]</c> and <c>List&lt;T&gt;</c> with <c>for</c>, other <c>ICollection&lt;T&gt;</c> with the size from
    /// <c>Count</c>, any other sequence with <c>foreach</c> (an array through a <c>List&lt;T&gt;</c>); a <see langword="null"/>
    /// source gives an empty list or <c>Array.Empty</c>. No static abstract interface members: every target framework.
    /// </summary>
    private static void EmitElementLoops(StringBuilder sb, bool usesList, bool usesArray, bool needsSeparator)
    {
        const string enumerable = "global::System.Collections.Generic.IEnumerable<TSource>";
        const string list = "global::System.Collections.Generic.List<TDest>";
        const string constraint = "            where TMapper : struct, " + ElementMapperInterface + "<TSource, TDest>";

        if (needsSeparator) sb.AppendLine();
        sb.AppendLine("        /// <summary>Maps one element; implemented by a private struct of each mapping that has MapToXList or MapToXArray.</summary>");
        sb.AppendLine($"        private interface {ElementMapperInterface}<TSource, TDest>");
        sb.AppendLine("        {");
        sb.AppendLine("            TDest Map(TSource source);");
        sb.AppendLine("        }");

        if (usesList)
        {
            sb.AppendLine();
            sb.AppendLine($"        private static {list} {ListHelperName}<TSource, TDest, TMapper>({enumerable}? source)");
            sb.AppendLine(constraint);
            sb.AppendLine("        {");
            sb.AppendLine("            var mapper = default(TMapper);");
            sb.AppendLine($"            if (source is null) return new {list}();");
            sb.AppendLine("            if (source is TSource[] array)");
            sb.AppendLine("            {");
            sb.AppendLine($"                var result = new {list}(array.Length);");
            sb.AppendLine("                for (var i = 0; i < array.Length; i++) result.Add(mapper.Map(array[i]));");
            sb.AppendLine("                return result;");
            sb.AppendLine("            }");
            sb.AppendLine("            if (source is global::System.Collections.Generic.List<TSource> list)");
            sb.AppendLine("            {");
            sb.AppendLine($"                var result = new {list}(list.Count);");
            sb.AppendLine("                for (var i = 0; i < list.Count; i++) result.Add(mapper.Map(list[i]));");
            sb.AppendLine("                return result;");
            sb.AppendLine("            }");
            sb.AppendLine("            {");
            sb.AppendLine("                var result = source is global::System.Collections.Generic.ICollection<TSource> collection");
            sb.AppendLine($"                    ? new {list}(collection.Count)");
            sb.AppendLine($"                    : new {list}();");
            sb.AppendLine("                foreach (var item in source) result.Add(mapper.Map(item));");
            sb.AppendLine("                return result;");
            sb.AppendLine("            }");
            sb.AppendLine("        }");
        }

        if (usesArray)
        {
            sb.AppendLine();
            sb.AppendLine($"        private static TDest[] {ArrayHelperName}<TSource, TDest, TMapper>({enumerable}? source)");
            sb.AppendLine(constraint);
            sb.AppendLine("        {");
            sb.AppendLine("            var mapper = default(TMapper);");
            sb.AppendLine("            if (source is null) return global::System.Array.Empty<TDest>();");
            sb.AppendLine("            if (source is TSource[] array)");
            sb.AppendLine("            {");
            sb.AppendLine("                var result = new TDest[array.Length];");
            sb.AppendLine("                for (var i = 0; i < array.Length; i++) result[i] = mapper.Map(array[i]);");
            sb.AppendLine("                return result;");
            sb.AppendLine("            }");
            sb.AppendLine("            if (source is global::System.Collections.Generic.List<TSource> list)");
            sb.AppendLine("            {");
            sb.AppendLine("                var result = new TDest[list.Count];");
            sb.AppendLine("                for (var i = 0; i < list.Count; i++) result[i] = mapper.Map(list[i]);");
            sb.AppendLine("                return result;");
            sb.AppendLine("            }");
            sb.AppendLine("            if (source is global::System.Collections.Generic.ICollection<TSource> collection)");
            sb.AppendLine("            {");
            sb.AppendLine("                var result = new TDest[collection.Count];");
            sb.AppendLine("                var i = 0;");
            sb.AppendLine("                foreach (var item in collection) result[i++] = mapper.Map(item);");
            sb.AppendLine("                return result;");
            sb.AppendLine("            }");
            sb.AppendLine("            {");
            sb.AppendLine($"                var result = new {list}();");
            sb.AppendLine("                foreach (var item in source) result.Add(mapper.Map(item));");
            sb.AppendLine("                return result.ToArray();");
            sb.AppendLine("            }");
            sb.AppendLine("        }");
        }
    }

    /// <summary>
    /// Generates the registration of the assembly's mappings for <c>IMapper</c>
    /// (<c>IronMapper.Registration.MapperRegistry</c>): a module initializer that hands the registration to the
    /// registry, and the registration itself (one <c>Register</c> call per mapping, with lambdas that call the generated
    /// methods directly). With C# 8 there is no <c>[ModuleInitializer]</c>; the user calls
    /// <c>GeneratedMappers_{AssemblyName}.RegisterIronMapperMappings()</c>. Without <c>ModuleInitializerAttribute</c> in the compilation
    /// (before .NET 5) the file also declares an internal copy, which the compiler recognizes by its full name.
    /// </summary>
    /// <param name="registrations">The generated mappings of the assembly; not empty.</param>
    /// <param name="options">APIs available in the user's compilation.</param>
    public static (string hintName, string source) EmitRegistration(EquatableArray<MappingRegistration> registrations,
        GeneratedCodeOptions options)
    {
        const string registry = "global::IronMapper.Registration.MapperRegistry";

        var sb = new StringBuilder();
        sb.AppendLine("// <auto-generated/>");
        sb.AppendLine("#nullable enable");
        sb.AppendLine();
        sb.AppendLine("namespace IronMapper.Generated");
        sb.AppendLine("{");
        sb.AppendLine($"    static partial class {options.ClassName}");
        sb.AppendLine("    {");
        sb.AppendLine($"        /// <summary>Adds the mappings of this assembly to <see cref=\"{registry}\"/> (used by <c>IMapper</c>).</summary>");
        if (options.SupportsModuleInitializers)
        {
            sb.AppendLine("        /// <remarks>Runs as the module initializer; the mappings are registered on the first use of the registry.</remarks>");
            sb.AppendLine("        [global::System.Runtime.CompilerServices.ModuleInitializer]");
        }
        else
        {
            sb.AppendLine("        /// <remarks>");
            sb.AppendLine("        /// C# 8 has no module initializers: call this method once at startup (before the first <c>IMapper</c> call),");
            sb.AppendLine("        /// or set <c>LangVersion</c> to 9 or later.");
            sb.AppendLine("        /// </remarks>");
        }
        // The check is here, not in AddAssembly: the trimmer replaces IsSupported with the feature switch and drops the
        // branch, and with it the only reference to RegisterIronMapperMappingsCore and the registry.
        sb.AppendLine("        internal static void RegisterIronMapperMappings()");
        sb.AppendLine("        {");
        sb.AppendLine($"            if ({registry}.IsSupported)");
        sb.AppendLine($"                {registry}.AddAssembly(RegisterIronMapperMappingsCore);");
        sb.AppendLine("        }");
        sb.AppendLine();
        sb.AppendLine("        private static void RegisterIronMapperMappingsCore()");
        sb.AppendLine("        {");
        foreach (var registration in registrations)
        {
            // A turned-off overload: in-place through the private method, List/Array as null (the registry loops itself).
            var method = registration.MethodName;
            var methods = registration.Methods;
            var mapInto = methods.InPlace ? method : PrivateInPlaceName(registration.HelperScope);
            sb.AppendLine($"            {registry}.Register<{registration.SourceFullName}, {registration.DestFullName}>(");
            sb.AppendLine($"                source => {method}(source),");
            sb.AppendLine($"                (source, destination) => {mapInto}(source, destination),");
            sb.AppendLine(methods.List ? $"                source => {method}List(source)," : "                null,");
            sb.AppendLine(methods.Array ? $"                source => {method}Array(source));" : "                null);");
        }
        sb.AppendLine("        }");
        sb.AppendLine("    }");
        sb.AppendLine("}");

        if (options.SupportsModuleInitializers && !options.HasModuleInitializerAttribute)
        {
            sb.AppendLine();
            sb.AppendLine("namespace System.Runtime.CompilerServices");
            sb.AppendLine("{");
            sb.AppendLine("    /// <summary>Declared by IronMapper: the target framework has no <c>ModuleInitializerAttribute</c> (added in .NET 5).</summary>");
            sb.AppendLine("    [global::System.AttributeUsage(global::System.AttributeTargets.Method, Inherited = false)]");
            sb.AppendLine("    internal sealed class ModuleInitializerAttribute : global::System.Attribute");
            sb.AppendLine("    {");
            sb.AppendLine("    }");
            sb.AppendLine("}");
        }

        // Per-mapping hint names always contain "_MapTo", so this one cannot collide with them.
        return ("GeneratedMappers.Registration.g.cs", sb.ToString());
    }

    /// <summary>
    /// Generates an empty <c>IronMapper.Generated</c> namespace for an assembly without generated mappings. The package
    /// adds <c>global using IronMapper.Generated;</c> (buildTransitive/IronMapper.props), which would otherwise fail
    /// with CS0246 in a project that has no mappings yet.
    /// </summary>
    public static (string hintName, string source) EmitEmptyNamespace()
    {
        var sb = new StringBuilder();
        sb.AppendLine("// <auto-generated/>");
