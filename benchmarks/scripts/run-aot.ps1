#Requires -Version 7.0
<#
.SYNOPSIS
    NativeAOT and trimming (BENCHMARK_SPEC.md, 9): warnings, does it work, executable size, AOT startup.
    Writes results/aot.md and results/aot-size-breakdown.md.

.DESCRIPTION
    Does not publish anything itself: the NativeAOT publish, the runs and the checksum check are done by
    run-startup.ps1 -Mode Aot (called here unless -ReportOnly), so the numbers in aot.md and startup.md come from the
    same binaries. This script then reads what that run left in results/raw/:
      - results/raw/startup-aot.csv          status (exit code + checksum vs Baseline and vs JIT) and AOT startup time;
      - results/raw/startup/publish-aot-*.log trim/AOT warnings (IL2xxx/IL3xxx, published with TrimmerSingleWarn=false);
      - results/raw/startup/publish/aot/*    executable sizes;
      - results/raw/startup/run-aot-*.stderr.txt  the exception of a probe that fails at runtime;
      - results/raw/startup/mstat/*.mstat    size breakdown (tools/MstatReport): IronMapper vs Mapperly vs Manual.

.EXAMPLE
    pwsh ./scripts/run-aot.ps1                 # publish + run (via run-startup.ps1 -Mode Aot) + reports
.EXAMPLE
    pwsh ./scripts/run-aot.ps1 -ReportOnly     # rebuild aot.md from the existing data
#>
[CmdletBinding()]
param(
    [int] $Runs = 30,
    [int] $WarmupRuns = 3,
    # Passed to run-startup.ps1: single-threaded ILC, and no free-memory confirmation.
    [switch] $LowMemory,
    [switch] $Force,
    # Only rebuild the reports from the existing data in results/raw/.
    [switch] $ReportOnly
)

$ErrorActionPreference = 'Stop'
Set-StrictMode -Version Latest
Import-Module (Join-Path $PSScriptRoot 'BenchmarkCommon.psm1') -Force

$reportPath = Join-Path (Get-ResultsDir) 'aot.md'
$breakdownPath = Join-Path (Get-ResultsDir) 'aot-size-breakdown.md'

if (-not $ReportOnly) {
    & (Join-Path $PSScriptRoot 'run-startup.ps1') -Mode Aot -Runs $Runs -WarmupRuns $WarmupRuns -LowMemory:$LowMemory -Force:$Force
}

$csv = Get-StartupCsvPath 'Aot'
if (-not (Test-Path $csv)) { throw "No NativeAOT measurements ($csv). Run without -ReportOnly first." }
$rows = @(Import-Csv $csv)
$jitChecksums = @{}
$jitCsv = Get-StartupCsvPath 'Jit'
if (Test-Path $jitCsv) { foreach ($r in Import-Csv $jitCsv) { $jitChecksums[$r.Probe] = $r.Checksum } }
$expected = $rows | Where-Object { $_.Probe -eq 'Baseline' -and $_.Status -eq 'ok' } | Select-Object -First 1 -ExpandProperty Checksum

# Exception summary of a probe that fails at runtime: the "Unhandled exception" line and the inner exceptions.
function Get-FailureSummary([string] $probe) {
    $path = Get-RunErrorPath 'Aot' $probe
    if (-not (Test-Path $path)) { return $null }
    $lines = Get-Content $path | Where-Object { $_ -match 'Unhandled exception|^\s*--->|Exception:' } |
        ForEach-Object { ($_ -replace '^\s*--->\s*', '→ ').Trim() } | Select-Object -Unique -First 4
    ($lines -join ' ')
}

$data = foreach ($r in $rows) {
    $exe = Get-ProbeExecutable (Get-ProbeDir 'Aot' $r.Probe) $r.Probe
    $works = $r.Status -eq 'ok' -and (-not $expected -or $r.Checksum -eq $expected) -and
        (-not $jitChecksums.ContainsKey($r.Probe) -or $jitChecksums[$r.Probe] -eq $r.Checksum)
    [pscustomobject]@{
        Probe    = $r.Probe
        Status   = $r.Status
        Works    = $works
        Size     = (Test-Path $exe) ? (Get-Item $exe).Length : $null
        MedianMs = $r.MedianMs
        Warnings = @(Get-IlWarnings (Get-PublishLogPath 'Aot' $r.Probe))
        Failure  = Get-FailureSummary $r.Probe
    }
}
$baseline = $data | Where-Object Probe -eq 'Baseline' | Select-Object -First 1
$meta = $rows | Select-Object -First 1

function Format-WarningCounts($warnings) {
    if ($warnings.Count -eq 0) { return 'none' }
    ($warnings | Group-Object Code | Sort-Object Name | ForEach-Object { "$($_.Name) ×$($_.Count)" }) -join ', '
}

$sb = [System.Text.StringBuilder]::new()
[void] $sb.AppendLine('# NativeAOT and trimming')
[void] $sb.AppendLine()
[void] $sb.AppendLine('> Generated by `scripts/run-aot.ps1` from the NativeAOT run of `scripts/run-startup.ps1`. Do not edit by hand.')
[void] $sb.AppendLine()
[void] $sb.AppendLine("$($meta.Date) UTC · $(Get-MachineSummary)")
[void] $sb.AppendLine()
[void] $sb.AppendLine("Each ``probes/StartupProbe.*`` console is published with ``dotnet publish -c Release -r $($meta.Rid) -p:PublishAot=true`` " +
    '(plus `-p:TrimmerSingleWarn=false` to list every warning and `-p:IlcGenerateMstatFile=true` for the size breakdown; neither changes the executable). ' +
    '**Works** means: the executable exited with 0 in every run and printed the same order checksum as the Baseline probe and as its own JIT build, i.e. the mapping really ran. ' +
    "Startup is the median wall-clock time of $($meta.Runs) runs (see [startup.md](startup.md)).")
[void] $sb.AppendLine()
[void] $sb.AppendLine('Sizes: 1 KB = 1,000 bytes, 1 MB = 1,000,000 bytes.')
[void] $sb.AppendLine()
[void] $sb.AppendLine('| Library | Warnings | Works in AOT | Executable size, bytes | Δ vs Baseline | AOT startup, ms | Δ startup vs Baseline, ms |')
[void] $sb.AppendLine('|---|---|---|---:|---:|---:|---:|')
foreach ($d in $data) {
    $works = if ($d.Works) { 'yes' } elseif ($d.Status -eq 'publish failed') { 'publish failed' } else { 'no' }
    if (-not $d.Works -and $d.Failure) { $works = "no — $(Format-Cell $d.Failure)" }
    $sizeDelta = if ($d.Size -and $baseline.Size) { Format-SignedSize ($d.Size - $baseline.Size) } else { '–' }
    $startupDelta = if ($d.Works -and $baseline.MedianMs) { Format-Ms ([double] $d.MedianMs - [double] $baseline.MedianMs) } else { '–' }
    $startup = if ($d.Works) { Format-Ms $d.MedianMs } else { '–' }
    [void] $sb.AppendLine("| $($d.Probe) | $(Format-WarningCounts $d.Warnings) | $works | $(Format-Bytes $d.Size) | $sizeDelta | $startup | $startupDelta |")
}
[void] $sb.AppendLine()

[void] $sb.AppendLine('## Findings')
[void] $sb.AppendLine()
# Facts of one probe from the data: warnings, works, startup Δ.
function Get-Facts([string] $probe) {
    $d = $data | Where-Object Probe -eq $probe | Select-Object -First 1
    if (-not $d) { return 'not measured' }
    $w = if ($d.Warnings.Count -eq 0) { 'no trim/AOT warnings' } else { "trim/AOT warnings ($(Format-WarningCounts $d.Warnings))" }
    if ($d.Status -eq 'publish failed') { return "$w, publish failed" }
    if (-not $d.Works) { return "$w, fails at runtime" }
    "$w, works, startup Δ $(Format-Ms ([double] $d.MedianMs - [double] $baseline.MedianMs)) ms vs Baseline"
}
function Test-Works([string] $probe) { [bool] ($data | Where-Object { $_.Probe -eq $probe -and $_.Works }) }

[void] $sb.AppendLine("- **IronMapper** (generated extension methods): $(Get-Facts 'IronMapper'). " +
    'This is the first actual NativeAOT check of IronMapper (`docs/advanced.md` lists it as "Not verified").')
[void] $sb.AppendLine("- **Mapperly**: $(Get-Facts 'Mapperly').")
$line = "- **IronMapper_IMapper** (``IMapper`` from ``IronMapper.Extensions.DI``): $(Get-Facts 'IronMapper_IMapper')."
if (-not (Test-Works 'IronMapper_IMapper')) {
    $line += ' `RuntimeMapper` finds the generated code by name (`assembly.GetType("IronMapper.Generated.GeneratedMappers")` + `GetMethods`), which the trimmer cannot see, ' +
        'so the method metadata is not kept and no mapping is registered. This confirms the documentation: the DI path is not NativeAOT-compatible; the generated extension methods are.'
}
[void] $sb.AppendLine($line)
[void] $sb.AppendLine("- **Mapster** (runtime configuration + ``Compile()``): $(Get-Facts 'Mapster'). " +
    'Mapster also has a code generation path, **Mapster.Tool** (a `dotnet tool` that generates mapper source as a separate build step), which is not measured here: ' +
    'it does not run as part of a plain `dotnet build` (BENCHMARK_SPEC.md, 2).')
[void] $sb.AppendLine("- **AutoMapper**: $(Get-Facts 'AutoMapper'). AutoMapper does not support NativeAOT: it builds the mapping code at runtime (expression trees, reflection).")
[void] $sb.AppendLine()

[void] $sb.AppendLine('## Executable size: IronMapper vs Mapperly')
[void] $sb.AppendLine()
$mstats = Get-MstatInputs 'Manual', 'IronMapper', 'Mapperly'
if ($mstats) {
    $breakdown = Invoke-MstatReport -Inputs $mstats -Diff 'IronMapper,Mapperly' -Top 25 -HeadingLevel 2
    $breakdownDoc = "# NativeAOT size breakdown: Manual, IronMapper, Mapperly`n`n" +
        "> Generated by ``scripts/run-aot.ps1`` with ``tools/MstatReport`` from the ILC mstat files of the NativeAOT probes. Do not edit by hand.`n`n" +
        "$($meta.Date) UTC · $(Get-MachineSummary)`n`n" + $breakdown
    Write-ReportFile $breakdownPath $breakdownDoc

    $im = $data | Where-Object Probe -eq 'IronMapper'
    $ml = $data | Where-Object Probe -eq 'Mapperly'
    [void] $sb.AppendLine("The IronMapper executable is $(Format-Size ($im.Size - $ml.Size)) larger than the Mapperly one. " +
        'Size by assembly from the ILC mstat files (full breakdown by namespace and type: [aot-size-breakdown.md](aot-size-breakdown.md)):')
    [void] $sb.AppendLine()
    [void] $sb.AppendLine((Get-MstatTable $breakdown 'Size by assembly'))
    [void] $sb.AppendLine()
    [void] $sb.AppendLine('The difference is not IronMapper code: the generated mappers take ~1.4 KB, and the IronMapper runtime assembly is not in the executable at all. ' +
        'It comes from how collections are mapped. IronMapper 1.1.3 generates `Enumerable.ToList(Enumerable.Select(source, x => x.MapToXxx()))`, ' +
        'Mapperly and Manual a loop into `new List<T>(count)`. The LINQ `Select` path contains generic virtual methods (`Iterator<T>.Select<TResult>`, ' +
        '`Utilities.CombineSelectors`) and `IList<T>` casts, which NativeAOT can only support with the runtime type loader: ' +
        '`System.Private.TypeLoader` grows by ~100 KB, and CoreLib gets more generic interface code (`IList<T>`, `ICollection<T>`, array enumerators) and the related data blobs. ' +
        'Checked in isolation (2026-10-18, .NET 10.0.12): two minimal consoles that differ only in `foreach` vs `Select` + `ToList` over a `List<T>` ' +
        'produce executables of 1,112,576 and 1,435,136 bytes, with the same +102,566 bytes in `System.Private.TypeLoader`. ' +
        'The cost is paid once per executable (it does not grow with the number of mappings), and any other `Select` in the application pays it as well.')
}
else {
    [void] $sb.AppendLine('_No mstat files for Manual, IronMapper and Mapperly: run `scripts/run-aot.ps1` (or `run-startup.ps1 -Mode Aot`) to publish them._')
}
[void] $sb.AppendLine()

[void] $sb.AppendLine('## Warnings by library')
[void] $sb.AppendLine()
[void] $sb.AppendLine('Every probe references only its own library, so the warnings of a probe are the warnings of that library. ' +
    'IL2104 / IL3053 are the per-assembly summaries ("Assembly X produced trim/AOT warnings"); the other codes are the individual warnings.')
[void] $sb.AppendLine()
foreach ($d in $data | Where-Object { $_.Warnings.Count -gt 0 }) {
    [void] $sb.AppendLine("### $($d.Probe)")
    [void] $sb.AppendLine()
    [void] $sb.AppendLine('| Code | Count |')
    [void] $sb.AppendLine('|---|---:|')
    foreach ($g in $d.Warnings | Group-Object Code | Sort-Object Name) { [void] $sb.AppendLine("| $($g.Name) | $($g.Count) |") }
    [void] $sb.AppendLine()
    $limit = 60
    [void] $sb.AppendLine('<details><summary>Warning messages</summary>')
    [void] $sb.AppendLine()
    foreach ($w in $d.Warnings | Sort-Object Code, Message | Select-Object -First $limit) {
        $origin = if ($w.Origin -match '\.(dll|exe)$') { Split-Path -Leaf $w.Origin } else { $w.Origin }
        $text = "$($w.Code) ($origin): $($w.Message)" -replace '\r?\n', ' '
        [void] $sb.AppendLine("- ``$($text -replace '`', "'")``")
    }
    if ($d.Warnings.Count -gt $limit) { [void] $sb.AppendLine("- … $($d.Warnings.Count - $limit) more in ``results/raw/startup/publish-aot-$($d.Probe).log``") }
    [void] $sb.AppendLine()
    [void] $sb.AppendLine('</details>')
    [void] $sb.AppendLine()
}
if (-not ($data | Where-Object { $_.Warnings.Count -gt 0 })) { [void] $sb.AppendLine('_No warnings._'); [void] $sb.AppendLine() }

Write-ReportFile $reportPath $sb.ToString()
