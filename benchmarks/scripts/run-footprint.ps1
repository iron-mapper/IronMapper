#Requires -Version 7.0
<#
.SYNOPSIS
    Size and dependencies (BENCHMARK_SPEC.md, 10). Writes results/footprint.md.

.DESCRIPTION
    - .nupkg size of each library package and its transitive dependencies (`dotnet list package --include-transitive`
      on the StartupProbe.<Lib> project, which references only that library); sizes from the NuGet global packages folder.
    - Size of the framework-dependent publish folder of each StartupProbe.<Lib> vs the Baseline probe.
    - Size of the NativeAOT executable vs Baseline, plus the mstat breakdown IronMapper vs Mapperly vs Manual.

    Reuses the probes published by run-startup.ps1 (results/raw/startup/publish/). Missing framework-dependent
    publishes are published here; NativeAOT data comes from run-aot.ps1 / run-startup.ps1 -Mode Aot only.

.EXAMPLE
    pwsh ./scripts/run-footprint.ps1
#>
[CmdletBinding()]
param()

$ErrorActionPreference = 'Stop'
Set-StrictMode -Version Latest
Import-Module (Join-Path $PSScriptRoot 'BenchmarkCommon.psm1') -Force

$reportPath = Join-Path (Get-ResultsDir) 'footprint.md'
$probes = Get-StartupProbeNames
$libraryProbes = $probes | Where-Object { $_ -notin 'Baseline', 'Manual' }

function Get-GlobalPackagesDir {
    if ($env:NUGET_PACKAGES) { return $env:NUGET_PACKAGES }
    $line = (& dotnet nuget locals global-packages --list) | Where-Object { $_ -match 'global-packages:\s*(.+)$' } | Select-Object -First 1
    if ($line -and $line -match 'global-packages:\s*(.+)$') { return $Matches[1].Trim() }
    throw 'Cannot determine the NuGet global packages folder.'
}
$packagesDir = Get-GlobalPackagesDir

function Get-NupkgSize([string] $id, [string] $version) {
    $lower = $id.ToLowerInvariant()
    $path = Join-Path $packagesDir $lower $version.ToLowerInvariant() "$lower.$($version.ToLowerInvariant()).nupkg"
    if (Test-Path $path) { return (Get-Item $path).Length }
    return $null
}

# Direct and transitive packages of a probe project (net10.0).
function Get-ProbePackages([string] $probe) {
    $project = Get-StartupProbeProject $probe
    $json = & dotnet list $project package --include-transitive --format json 2>$null
    if ($LASTEXITCODE -ne 0) {
        & dotnet restore $project -nologo -v q | Out-Null
        $json = & dotnet list $project package --include-transitive --format json
    }
    $parsed = ($json -join "`n") | ConvertFrom-Json
    $framework = $parsed.projects[0].frameworks | Select-Object -First 1
    $result = @()
    foreach ($p in @($framework.PSObject.Properties['topLevelPackages'] ? $framework.topLevelPackages : @())) {
        $result += [pscustomobject]@{ Id = $p.id; Version = $p.resolvedVersion; Direct = $true; Size = Get-NupkgSize $p.id $p.resolvedVersion }
    }
    foreach ($p in @($framework.PSObject.Properties['transitivePackages'] ? $framework.transitivePackages : @())) {
        $result += [pscustomobject]@{ Id = $p.id; Version = $p.resolvedVersion; Direct = $false; Size = Get-NupkgSize $p.id $p.resolvedVersion }
    }
    $result
}

# --- framework-dependent publish (reuse run-startup.ps1 output, publish what is missing) ---
$jit = @{}
foreach ($probe in $probes) {
    $dir = Get-ProbeDir 'Jit' $probe
    if (-not (Test-Path (Get-ProbeExecutable $dir $probe))) {
        Write-Host "Publishing $probe (Jit)..."
        $r = Publish-StartupProbe -Probe $probe -Mode Jit
        if (-not $r.Ok) { Write-Warning "Publish failed: $probe; see $($r.Log)"; continue }
    }
    $jit[$probe] = Measure-PublishFolder $dir
}

# --- packages ---
$packages = @{}
foreach ($probe in $libraryProbes) { $packages[$probe] = @(Get-ProbePackages $probe) }

# --- NativeAOT (from run-aot.ps1 / run-startup.ps1 -Mode Aot) ---
$aotRows = @{}
$aotCsv = Get-StartupCsvPath 'Aot'
if (Test-Path $aotCsv) { foreach ($r in Import-Csv $aotCsv) { $aotRows[$r.Probe] = $r } }
$aot = @{}
foreach ($probe in $probes) {
    $exe = Get-ProbeExecutable (Get-ProbeDir 'Aot' $probe) $probe
    if (Test-Path $exe) { $aot[$probe] = (Get-Item $exe).Length }
}

$sb = [System.Text.StringBuilder]::new()
[void] $sb.AppendLine('# Size and dependencies')
[void] $sb.AppendLine()
[void] $sb.AppendLine('> Generated by `scripts/run-footprint.ps1`. Do not edit by hand.')
[void] $sb.AppendLine()
[void] $sb.AppendLine("$(Get-UtcStamp) · $(Get-MachineSummary)")
[void] $sb.AppendLine()

[void] $sb.AppendLine('## NuGet packages')
[void] $sb.AppendLine()
[void] $sb.AppendLine('Packages of each `probes/StartupProbe.<Lib>` project (it references only that library), from `dotnet list package --include-transitive` (net10.0). ' +
    'A `.nupkg` contains every target framework, analyzers / source generators and XML docs of the package, so it says little about what an application ships; ' +
    'for that see the publish sizes below.')
[void] $sb.AppendLine()
[void] $sb.AppendLine('| Library | Direct packages | .nupkg size (direct) | Transitive packages | .nupkg size (all) |')
[void] $sb.AppendLine('|---|---|---:|---|---:|')
foreach ($probe in $libraryProbes) {
    $all = $packages[$probe]
    $direct = @($all | Where-Object Direct)
    $transitive = @($all | Where-Object { -not $_.Direct })
    $directText = ($direct | ForEach-Object { "$($_.Id) $($_.Version)" }) -join '<br>'
    $transitiveText = if ($transitive.Count) { ($transitive | Sort-Object Id | ForEach-Object { "$($_.Id) $($_.Version)" }) -join '<br>' } else { '–' }
    $directSize = ($direct | Measure-Object -Property Size -Sum).Sum
    $allSize = ($all | Measure-Object -Property Size -Sum).Sum
    [void] $sb.AppendLine("| $probe | $directText | $(Format-Size $directSize) | $transitiveText | $(Format-Size $allSize) |")
}
[void] $sb.AppendLine()
[void] $sb.AppendLine('<details><summary>Size of every package</summary>')
[void] $sb.AppendLine()
[void] $sb.AppendLine('| Package | Version | .nupkg size |')
[void] $sb.AppendLine('|---|---|---:|')
$unique = $packages.Values | ForEach-Object { $_ } | Sort-Object Id, Version -Unique
foreach ($p in $unique) { [void] $sb.AppendLine("| $($p.Id) | $($p.Version) | $(Format-Bytes $p.Size) |") }
[void] $sb.AppendLine()
[void] $sb.AppendLine('</details>')
[void] $sb.AppendLine()

[void] $sb.AppendLine('## Framework-dependent publish')
[void] $sb.AppendLine()
[void] $sb.AppendLine('`dotnet publish -c Release -r <rid> --self-contained false` of each probe; all files except `.pdb`. ' +
    'The probe assembly contains the mapping configuration (and, for the source generators, the generated code), so it is part of the size. ' +
    '"Added files" are the files that the Baseline publish does not have, apart from the probe''s own files.')
[void] $sb.AppendLine()
[void] $sb.AppendLine('| Library | Files | Size | Δ vs Baseline | Added files |')
[void] $sb.AppendLine('|---|---:|---:|---:|---|')
$baseJit = $jit['Baseline']
foreach ($probe in $probes) {
    if (-not $jit.ContainsKey($probe)) { [void] $sb.AppendLine("| $probe | – | – | – | publish failed |"); continue }
    $j = $jit[$probe]
    $added = @($j.Names | Where-Object { $_ -notlike "StartupProbe.$probe.*" -and $_ -notin $baseJit.Names } | Sort-Object)
    $addedText = if ($added.Count) { $added -join '<br>' } else { '–' }
    [void] $sb.AppendLine("| $probe | $($j.Files) | $(Format-Size $j.Size) | $(Format-SignedSize ($j.Size - $baseJit.Size)) | $addedText |")
}
[void] $sb.AppendLine()

[void] $sb.AppendLine('## NativeAOT executable')
[void] $sb.AppendLine()
if ($aot.Count -eq 0) {
    [void] $sb.AppendLine('_No NativeAOT executables: run `scripts/run-aot.ps1` first._')
}
else {
    [void] $sb.AppendLine('From the NativeAOT publish of `scripts/run-aot.ps1` (details, warnings and startup: [aot.md](aot.md)). ' +
        'A size is shown for every executable that was produced, also when it fails at runtime.')
    [void] $sb.AppendLine()
    [void] $sb.AppendLine('| Library | Executable size | Δ vs Baseline | Works in AOT |')
    [void] $sb.AppendLine('|---|---:|---:|---|')
    foreach ($probe in $probes) {
        if (-not $aot.ContainsKey($probe)) { [void] $sb.AppendLine("| $probe | – | – | publish failed |"); continue }
        $works = if ($aotRows.ContainsKey($probe) -and $aotRows[$probe].Status -eq 'ok') { 'yes' } else { 'no' }
        $delta = if ($aot.ContainsKey('Baseline')) { Format-SignedSize ($aot[$probe] - $aot['Baseline']) } else { '–' }
        [void] $sb.AppendLine("| $probe | $(Format-Size $aot[$probe]) | $delta | $works |")
    }
    [void] $sb.AppendLine()

    $mstats = Get-MstatInputs 'Manual', 'IronMapper', 'Mapperly'
    if ($mstats -and $aot.ContainsKey('IronMapper') -and $aot.ContainsKey('Mapperly')) {
        $breakdown = Invoke-MstatReport -Inputs $mstats -Diff 'IronMapper,Mapperly' -Top 10 -HeadingLevel 3
        [void] $sb.AppendLine('### IronMapper vs Mapperly')
        [void] $sb.AppendLine()
        [void] $sb.AppendLine("The IronMapper executable is $(Format-Size ($aot['IronMapper'] - $aot['Mapperly'])) larger than the Mapperly one. " +
            'Almost all of it is the NativeAOT runtime type loader (`System.Private.TypeLoader`) and generic collection code in CoreLib, pulled in by ' +
            'the `Enumerable.Select` + `ToList` that IronMapper 1.1.3 generates for collection properties (Mapperly and Manual use a loop). ' +
            'It is a fixed cost per executable, not per mapping; explanation and verification in [aot.md](aot.md#executable-size-ironmapper-vs-mapperly), ' +
            'full breakdown in [aot-size-breakdown.md](aot-size-breakdown.md). Size by assembly (ILC mstat, bytes):')
        [void] $sb.AppendLine()
        [void] $sb.AppendLine((Get-MstatTable $breakdown 'Size by assembly'))
        [void] $sb.AppendLine()
    }
}

Write-ReportFile $reportPath $sb.ToString()
