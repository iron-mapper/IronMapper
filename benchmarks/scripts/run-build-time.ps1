#Requires -Version 7.0
<#
.SYNOPSIS
    Build time impact (BENCHMARK_SPEC.md, 11). Generates probes/BuildProbe.<Lib>.N<n>, times their builds and writes
    results/build-time.md.

.DESCRIPTION
    Source generators do their work at compile time, runtime mappers at startup; this script shows the compile side
    (the startup side is in startup.md).

    Generated projects (not committed, see .gitignore), one per library and size N (default 50 and 200):
      - Models.cs, identical in every project: N entity/DTO pairs Item{i}Entity → Item{i}Dto with 10 properties
        (int, long, string ×2, decimal, bool, DateTime, Guid, int?, enum). Every 4th pair also has a collection of the
        previous pair (List<Item{i-1}Entity> Children), every 4th pair with offset 2 a single nested object of the
        previous pair (Item{i-1}Entity Parent). Nesting only references pairs that already exist, so a project has
        exactly N pairs, and each pair is configured exactly once (IronMapper: one definition per type pair, IM0007).
      - Mapping.cs, one per library, each configured the way the library is meant to be used:
          Baseline    no mapper (models only)
          Manual      hand-written extension methods (loop for collections)
          IronMapper  MappingProfile: CreateMap per pair; the single nested object needs
                      ForMember(d => d.Parent, o => o.MapFrom(s => s.Parent.MapToItem{i-1}Dto())) — IronMapper does not
                      map nested single objects automatically; collections are automatic
          Mapperly    [Mapper] static partial class, one partial method per pair (nested types use the other methods)
          Mapster     TypeAdapterConfig: NewConfig per pair + Compile()
          AutoMapper  Profile: CreateMap per pair

    Measurement per project ("series"): `dotnet build-server shutdown`, restore, WarmupRuns builds, then Runs timed
    `dotnet build --no-incremental -c Release --no-restore` (wall-clock); the build servers stay up within a series.
    With hyperfine on PATH it is used for the timing (unless -NoHyperfine). After the series, one more build (not timed)
    with -p:ReportAnalyzer=true reports the generator execution time and emits the generated files, so the script can
    check that every pair was really generated.

.EXAMPLE
    pwsh ./scripts/run-build-time.ps1
.EXAMPLE
    pwsh ./scripts/run-build-time.ps1 -Sizes 50 -Runs 5      # quick check
    pwsh ./scripts/run-build-time.ps1 -ReportOnly            # rebuild build-time.md from results/raw/build-time.csv
#>
[CmdletBinding()]
param(
    [int[]] $Sizes = @(50, 200),
    [int] $Runs = 10,
    [int] $WarmupRuns = 2,
    [ValidateSet('Baseline', 'Manual', 'IronMapper', 'Mapperly', 'Mapster', 'AutoMapper')]
    [string[]] $Libraries = @('Baseline', 'Manual', 'IronMapper', 'Mapperly', 'Mapster', 'AutoMapper'),
    # Only generate the projects.
    [switch] $GenerateOnly,
    # Only rebuild results/build-time.md from results/raw/build-time.csv.
    [switch] $ReportOnly,
    # Time the builds with the script's own stopwatch even if hyperfine is available.
    [switch] $NoHyperfine
)

$ErrorActionPreference = 'Stop'
Set-StrictMode -Version Latest
Import-Module (Join-Path $PSScriptRoot 'BenchmarkCommon.psm1') -Force

$probesDir = Join-Path (Get-BenchmarksDir) 'probes'
$rawDir = Join-Path (Get-ResultsRawDir) 'build-time'
$csvPath = Join-Path (Get-ResultsRawDir) 'build-time.csv'
$reportPath = Join-Path (Get-ResultsDir) 'build-time.md'

