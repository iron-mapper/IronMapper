function Get-NestKind([int] $i) {
    if ($i -gt 1 -and $i % 4 -eq 0) { return 'Collection' }
    if ($i -gt 1 -and $i % 4 -eq 2) { return 'Single' }
    return 'None'
}

function New-ModelsSource([int] $n) {
    $sb = [System.Text.StringBuilder]::new()
    [void] $sb.AppendLine('// Generated by scripts/run-build-time.ps1. Identical in every BuildProbe project of this size.')
    [void] $sb.AppendLine('namespace BuildProbe.Models;')
    [void] $sb.AppendLine()
    [void] $sb.AppendLine('public enum ItemState { Draft, Active, Archived }')
    foreach ($i in 1..$n) {
        foreach ($suffix in 'Entity', 'Dto') {
            [void] $sb.AppendLine()
            [void] $sb.AppendLine("public sealed class Item$i$suffix")
            [void] $sb.AppendLine('{')
            [void] $sb.AppendLine('    public int Id { get; set; }')
            [void] $sb.AppendLine('    public long Version { get; set; }')
            [void] $sb.AppendLine('    public string Name { get; set; } = "";')
            [void] $sb.AppendLine('    public string Code { get; set; } = "";')
            [void] $sb.AppendLine('    public decimal Amount { get; set; }')
            [void] $sb.AppendLine('    public bool IsActive { get; set; }')
            [void] $sb.AppendLine('    public DateTime CreatedAt { get; set; }')
            [void] $sb.AppendLine('    public Guid Key { get; set; }')
            [void] $sb.AppendLine('    public int? Priority { get; set; }')
            [void] $sb.AppendLine('    public ItemState State { get; set; }')
            $prev = $i - 1
            switch (Get-NestKind $i) {
                'Collection' { [void] $sb.AppendLine("    public List<Item$prev$suffix> Children { get; set; } = [];") }
                'Single' { [void] $sb.AppendLine("    public Item$prev$suffix Parent { get; set; } = new();") }
            }
            [void] $sb.AppendLine('}')
        }
    }
    $sb.ToString()
}

$scalarProperties = 'Id', 'Version', 'Name', 'Code', 'Amount', 'IsActive', 'CreatedAt', 'Key', 'Priority', 'State'

function New-MappingSource([string] $lib, [int] $n) {
    $sb = [System.Text.StringBuilder]::new()
    [void] $sb.AppendLine('// Generated by scripts/run-build-time.ps1.')
    switch ($lib) {
        'Manual' {
            [void] $sb.AppendLine('using BuildProbe.Models;')
            [void] $sb.AppendLine()
            [void] $sb.AppendLine('namespace BuildProbe.Mapping;')
            [void] $sb.AppendLine()
            [void] $sb.AppendLine('public static class ManualMappings')
            [void] $sb.AppendLine('{')
            foreach ($i in 1..$n) {
                $prev = $i - 1
                [void] $sb.AppendLine("    public static Item${i}Dto ToItem${i}Dto(this Item${i}Entity s) => new()")
                [void] $sb.AppendLine('    {')
                foreach ($p in $scalarProperties) { [void] $sb.AppendLine("        $p = s.$p,") }
                switch (Get-NestKind $i) {
                    'Collection' { [void] $sb.AppendLine("        Children = MapList(s.Children, static x => x.ToItem${prev}Dto()),") }
                    'Single' { [void] $sb.AppendLine("        Parent = s.Parent.ToItem${prev}Dto(),") }
                }
                [void] $sb.AppendLine('    };')
                [void] $sb.AppendLine()
            }
            [void] $sb.AppendLine('    private static List<TDest> MapList<TSource, TDest>(List<TSource> source, Func<TSource, TDest> map)')
            [void] $sb.AppendLine('    {')
            [void] $sb.AppendLine('        var result = new List<TDest>(source.Count);')
            [void] $sb.AppendLine('        foreach (var item in source) result.Add(map(item));')
            [void] $sb.AppendLine('        return result;')
            [void] $sb.AppendLine('    }')
            [void] $sb.AppendLine('}')
        }
        'IronMapper' {
            [void] $sb.AppendLine('using BuildProbe.Models;')
            [void] $sb.AppendLine('using IronMapper.Configuration;')
            [void] $sb.AppendLine('using IronMapper.Generated;')
            [void] $sb.AppendLine()
            [void] $sb.AppendLine('namespace BuildProbe.Mapping;')
            [void] $sb.AppendLine()
            [void] $sb.AppendLine('public sealed class BuildProbeProfile : MappingProfile')
            [void] $sb.AppendLine('{')
            [void] $sb.AppendLine('    public BuildProbeProfile()')
            [void] $sb.AppendLine('    {')
            foreach ($i in 1..$n) {
                $prev = $i - 1
                if ((Get-NestKind $i) -eq 'Single') {
                    # Nested single objects are not mapped automatically (docs/advanced.md, "Nested objects").
                    [void] $sb.AppendLine("        CreateMap<Item${i}Entity, Item${i}Dto>()")
                    [void] $sb.AppendLine("            .ForMember(d => d.Parent, o => o.MapFrom(s => s.Parent.MapToItem${prev}Dto()));")
                }
                else { [void] $sb.AppendLine("        CreateMap<Item${i}Entity, Item${i}Dto>();") }
            }
            [void] $sb.AppendLine('    }')
            [void] $sb.AppendLine('}')
        }
        'Mapperly' {
            [void] $sb.AppendLine('using BuildProbe.Models;')
            [void] $sb.AppendLine('using Riok.Mapperly.Abstractions;')
            [void] $sb.AppendLine()
            [void] $sb.AppendLine('namespace BuildProbe.Mapping;')
            [void] $sb.AppendLine()
            [void] $sb.AppendLine('[Mapper]')
            [void] $sb.AppendLine('public static partial class BuildProbeMapper')
            [void] $sb.AppendLine('{')
            foreach ($i in 1..$n) { [void] $sb.AppendLine("    public static partial Item${i}Dto ToItem${i}Dto(this Item${i}Entity source);") }
            [void] $sb.AppendLine('}')
        }
        'Mapster' {
            [void] $sb.AppendLine('using BuildProbe.Models;')
            [void] $sb.AppendLine('using Mapster;')
            [void] $sb.AppendLine()
            [void] $sb.AppendLine('namespace BuildProbe.Mapping;')
            [void] $sb.AppendLine()
            [void] $sb.AppendLine('public static class BuildProbeMapsterConfig')
            [void] $sb.AppendLine('{')
            [void] $sb.AppendLine('    public static TypeAdapterConfig CreateConfig()')
            [void] $sb.AppendLine('    {')
            [void] $sb.AppendLine('        var config = new TypeAdapterConfig();')
            foreach ($i in 1..$n) { [void] $sb.AppendLine("        config.NewConfig<Item${i}Entity, Item${i}Dto>();") }
            [void] $sb.AppendLine('        config.Compile();')
            [void] $sb.AppendLine('        return config;')
            [void] $sb.AppendLine('    }')
            [void] $sb.AppendLine('}')
        }
        'AutoMapper' {
            [void] $sb.AppendLine('using AutoMapper;')
            [void] $sb.AppendLine('using BuildProbe.Models;')
            [void] $sb.AppendLine()
            [void] $sb.AppendLine('namespace BuildProbe.Mapping;')
            [void] $sb.AppendLine()
            [void] $sb.AppendLine('public sealed class BuildProbeProfile : Profile')
            [void] $sb.AppendLine('{')
            [void] $sb.AppendLine('    public BuildProbeProfile()')
            [void] $sb.AppendLine('    {')
            foreach ($i in 1..$n) { [void] $sb.AppendLine("        CreateMap<Item${i}Entity, Item${i}Dto>();") }
            [void] $sb.AppendLine('    }')
            [void] $sb.AppendLine('}')
        }
    }
    $sb.ToString()
}

function New-ProjectSource([string] $lib) {
    $props = ''
    $refs = ''
    switch ($lib) {
        'IronMapper' { $props = "`n    <UsesIronMapper>true</UsesIronMapper>" }
        'Mapperly' { $refs = '<PackageReference Include="Riok.Mapperly" />' }
        'Mapster' { $refs = '<PackageReference Include="Mapster" />' }
        'AutoMapper' { $refs = '<PackageReference Include="AutoMapper" />' }
    }
    $itemGroup = if ($refs) { "`n  <ItemGroup>`n    $refs`n  </ItemGroup>`n" } else { '' }
    @"
<Project Sdk="Microsoft.NET.Sdk">

  <!-- Generated by scripts/run-build-time.ps1 (BENCHMARK_SPEC.md, 11). Not committed. -->
  <PropertyGroup>
    <OutputType>Library</OutputType>$props
  </PropertyGroup>
$itemGroup
</Project>
"@
}

function Get-ProbeName([string] $lib, [int] $n) { "BuildProbe.$lib.N$n" }

function Get-BuildProbeProject([string] $lib, [int] $n) {
    $name = Get-ProbeName $lib $n
    Join-Path $probesDir $name "$name.csproj"
}

function New-BuildProbe([string] $lib, [int] $n, [string] $models) {
    $project = Get-BuildProbeProject $lib $n
    $dir = Split-Path -Parent $project
    if (Test-Path $dir) { Remove-Item -Recurse -Force $dir }
    New-Item -ItemType Directory -Force -Path $dir | Out-Null
    $utf8 = [System.Text.UTF8Encoding]::new($false)
    [System.IO.File]::WriteAllText($project, (New-ProjectSource $lib), $utf8)
    [System.IO.File]::WriteAllText((Join-Path $dir 'Models.cs'), $models, $utf8)
    if ($lib -ne 'Baseline') { [System.IO.File]::WriteAllText((Join-Path $dir 'Mapping.cs'), (New-MappingSource $lib $n), $utf8) }
    $project
}

