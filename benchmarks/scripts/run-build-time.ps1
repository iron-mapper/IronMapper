# Files / lines / size of the code emitted by the library's own generator (from the not-timed ReportAnalyzer build).
function Get-GeneratedCodeSummary([string] $lib, [int] $n) {
    $generatorDir = switch ($lib) { 'IronMapper' { 'IronMapper.Generator' } 'Mapperly' { 'Riok.Mapperly' } default { return '–' } }
    $dir = Join-Path $rawDir "$(Get-ProbeName $lib $n).generated" $generatorDir
    if (-not (Test-Path $dir)) { return '–' }
    $files = @(Get-ChildItem -Path $dir -Recurse -Filter *.cs)
    $lines = ($files | ForEach-Object { (Get-Content $_.FullName).Count } | Measure-Object -Sum).Sum
    $bytes = ($files | Measure-Object -Property Length -Sum).Sum
    "$($files.Count) $($files.Count -eq 1 ? 'file' : 'files'), $($lines.ToString('N0', [cultureinfo]::InvariantCulture)) lines, $(Format-Size $bytes)"
}

function Write-BuildTimeReport {
    if (-not (Test-Path $csvPath)) { throw "No measurements ($csvPath). Run without -ReportOnly first." }
    $rows = @(Import-Csv $csvPath)
    $meta = $rows | Select-Object -First 1

    $sb = [System.Text.StringBuilder]::new()
    [void] $sb.AppendLine('# Build time')
    [void] $sb.AppendLine()
    [void] $sb.AppendLine('> Generated by `scripts/run-build-time.ps1` from `results/raw/build-time.csv`. Do not edit by hand.')
    [void] $sb.AppendLine()
    [void] $sb.AppendLine("$($meta.Date) · $(Get-MachineSummary)")
    [void] $sb.AppendLine()
    [void] $sb.AppendLine('Source generators work at compile time, runtime mappers at startup ([startup.md](startup.md)); this page shows the compile side.')
    [void] $sb.AppendLine()
    [void] $sb.AppendLine('**Projects.** For each library and N, `scripts/run-build-time.ps1` generates a class library `probes/BuildProbe.<Lib>.N<N>` (not committed). ' +
        'The models are identical in every project: N entity/DTO pairs with 10 properties (int, long, two strings, decimal, bool, DateTime, Guid, int?, enum); ' +
        'every 4th pair adds a `List<>` of the previous pair, every 4th pair with offset 2 a single nested object of the previous pair. ' +
        'Nesting only references existing pairs, so each project has exactly N pairs and each pair is configured once. ' +
        '`Baseline` has the models only. Mapping configuration: `Manual` hand-written extension methods; `IronMapper` a `MappingProfile` with `CreateMap` per pair, ' +
        'the single nested objects via `ForMember(... MapFrom(s => s.Parent.MapToItemXDto()))` because IronMapper does not map them automatically (collections are automatic); ' +
        '`Mapperly` a `[Mapper]` class with one partial method per pair; `Mapster` `NewConfig` per pair; `AutoMapper` a `Profile` with `CreateMap` per pair.')
    [void] $sb.AppendLine()
    [void] $sb.AppendLine("**Measurement.** Per project: ``dotnet build-server shutdown``, restore, $($meta.WarmupRuns) warmup builds, then $($meta.Runs) timed " +
        '`dotnet build --no-incremental -c Release --no-restore` (wall-clock, timer: ' + $meta.Timer + '). The build servers stay running within a project''s series, ' +
        'as in a normal edit-build loop. `--no-restore` keeps the (identical) restore check out of the numbers. ' +
        '**Generator, s** is the execution time of the library''s source generator in one more build with `-p:ReportAnalyzer=true` (not timed); ' +
        '**Generated** counts the mapping methods found in the emitted generated sources (must equal N); **Generated code** is the size of those sources.')
    [void] $sb.AppendLine()

    foreach ($n in $rows.N | Sort-Object { [int] $_ } -Unique) {
        $group = $rows | Where-Object N -eq $n
        $baseline = $group | Where-Object Library -eq 'Baseline' | Select-Object -First 1
        [void] $sb.AppendLine("## N = $n")
        [void] $sb.AppendLine()
        [void] $sb.AppendLine('| Library | Median, s | Min, s | Max, s | Std dev, s | Δ median vs Baseline, s | Δ per pair, ms | Generator, s | Generated | Generated code | Warnings |')
        [void] $sb.AppendLine('|---|---:|---:|---:|---:|---:|---:|---:|---:|---:|---:|')
        foreach ($r in $group) {
            $delta = if ($baseline) { [double] $r.MedianS - [double] $baseline.MedianS } else { $null }
            $perPair = if ($null -ne $delta -and $r.Library -ne 'Baseline') { (1000 * $delta / [int] $n).ToString('N1', [cultureinfo]::InvariantCulture) } else { '–' }
            $generated = if ($r.GeneratedMappings) { "$($r.GeneratedMappings) / $n" } else { '–' }
            $deltaText = if ($r.Library -eq 'Baseline') { '0.00' } else { Format-SignedSeconds $delta }
            [void] $sb.AppendLine("| $($r.Library) | $(Format-Seconds $r.MedianS) | $(Format-Seconds $r.MinS) | $(Format-Seconds $r.MaxS) | $(Format-Seconds $r.StdDevS) | $deltaText | $perPair | $(Format-Seconds $r.GeneratorS) | $generated | $(Get-GeneratedCodeSummary $r.Library ([int] $n)) | $($r.Warnings) |")
        }
        [void] $sb.AppendLine()
    }

    [void] $sb.AppendLine('Notes:')
    [void] $sb.AppendLine()
    [void] $sb.AppendLine('- Δ vs Baseline includes everything the library adds to a build: the reference (and its analyzers), compiling the configuration code, and for the source generators the generator run and compiling the generated code.')
    [void] $sb.AppendLine('- IronMapper and Mapperly spend about the same time in the generator itself; the rest of the difference is compiling the generated code. ' +
        'IronMapper 1.1.3 emits one file per pair with a mapping method and an in-place overload (with `ArgumentNullException` checks and LINQ for collections), ' +
        'Mapperly one file with one method per pair, so IronMapper gives the compiler several times more code (see **Generated code**).')
    [void] $sb.AppendLine('- Differences of a few tens of milliseconds are within the noise of a single build; compare the medians together with the min/max.')
    [void] $sb.AppendLine('- The generated projects, the warnings of the warmup builds and the ReportAnalyzer logs are kept in `probes/BuildProbe.*` and `results/raw/build-time/`.')
    [void] $sb.AppendLine()

    Write-ReportFile $reportPath $sb.ToString()
}

