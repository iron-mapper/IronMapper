function Invoke-Build([string] $project, [string[]] $extra = @()) {
    $out = & dotnet build $project --no-incremental -c Release --no-restore -nologo -v q @extra 2>&1
    [pscustomobject]@{ ExitCode = $LASTEXITCODE; Output = @($out | ForEach-Object { "$_" }) }
}

function Measure-WithStopwatch([string] $project) {
    $times = [System.Collections.Generic.List[double]]::new()
    foreach ($i in 1..$Runs) {
        $sw = [System.Diagnostics.Stopwatch]::StartNew()
        $r = Invoke-Build $project
        $sw.Stop()
        if ($r.ExitCode -ne 0) { throw "Build failed: $project`n$($r.Output -join "`n")" }
        $times.Add($sw.Elapsed.TotalSeconds)
    }
    , $times.ToArray()
}

function Measure-WithHyperfine([string] $project, [string] $name) {
    $json = Join-Path $rawDir "$name.hyperfine.json"
    $command = "dotnet build `"$project`" --no-incremental -c Release --no-restore -nologo -v q"
    & hyperfine --runs $Runs --warmup 0 --shell=none --export-json $json $command | Out-Null
    if ($LASTEXITCODE -ne 0) { throw "hyperfine failed for $project" }
    , ([double[]] (Get-Content $json -Raw | ConvertFrom-Json).results[0].times)
}

# Generator execution time per generator assembly (objects with Name, Seconds) from a -p:ReportAnalyzer=true build log.
function Get-GeneratorTimes([string[]] $lines) {
    $count = 0
    $inGenerators = $false
    # MSBuild forwards the csc output as one message with embedded line breaks.
    foreach ($line in ($lines -split '\r?\n')) {
        if ($line -match 'Total generator execution time:\s*([\d.,]+)') { $inGenerators = $true; continue }
        if ($inGenerators -and $line -match 'Total analyzer execution time') { $inGenerators = $false; continue }
        if (-not $inGenerators) { continue }
        # Assembly lines: "   0.123   45   Riok.Mapperly, Version=4.3.1.0, Culture=neutral, PublicKeyToken=null"
        if ($line -match '^\s*(?<t>[\d.,<]+)\s+(?<p>[\d<]+)\s+(?<name>[A-Za-z][\w.]*), Version=') {
            $t = $Matches.t -replace ',', '.' -replace '<', ''
            $count++
            [pscustomobject]@{ Name = $Matches.name; Seconds = [double]::Parse($t, [cultureinfo]::InvariantCulture) }
        }
        elseif ($line.Trim() -eq '' -and $count) { $inGenerators = $false }
    }
}

# Count of generated mapping methods in the emitted generated sources, $null for libraries without a generator.
function Get-GeneratedMappingCount([string] $lib, [string] $generatedDir) {
    if ($lib -notin 'IronMapper', 'Mapperly') { return $null }
    if (-not (Test-Path $generatedDir)) { return 0 }
    $files = Get-ChildItem -Path $generatedDir -Recurse -Filter *.cs
    $names = [System.Collections.Generic.HashSet[string]]::new()
    $pattern = if ($lib -eq 'IronMapper') { '\bMapToItem(\d+)Dto\s*\(\s*this\b' } else { 'partial\s+[\w.:]*Item\d+Dto\s+ToItem(\d+)Dto\s*\(' }
    foreach ($f in $files) {
        foreach ($m in [regex]::Matches((Get-Content $f.FullName -Raw), $pattern)) { [void] $names.Add($m.Groups[1].Value) }
    }
    $names.Count
}

function Measure-BuildProbe([string] $lib, [int] $n) {
    $project = Get-BuildProbeProject $lib $n
    $name = Get-ProbeName $lib $n
    Write-Host "Measuring $name..."

    & dotnet build-server shutdown *> $null
    & dotnet restore $project -nologo -v q *> (Join-Path $rawDir "$name.restore.log")
    if ($LASTEXITCODE -ne 0) { throw "Restore failed: $project" }

    $warnings = [System.Collections.Generic.HashSet[string]]::new()
    foreach ($i in 1..$WarmupRuns) {
        $r = Invoke-Build $project
        if ($r.ExitCode -ne 0) { throw "Build failed: $project`n$($r.Output -join "`n")" }
        foreach ($l in $r.Output | Where-Object { $_ -match ': warning [A-Z]+\d+' }) { [void] $warnings.Add(($l -replace '\s+\[[^\]]+\]\s*$', '').Trim()) }
    }
    Set-Content -Path (Join-Path $rawDir "$name.warnings.txt") -Value ($warnings -join "`n") -Encoding utf8NoBOM

    $useHyperfine = -not $NoHyperfine -and (Get-Command hyperfine -ErrorAction SilentlyContinue)
    $times = if ($useHyperfine) { Measure-WithHyperfine $project $name } else { Measure-WithStopwatch $project }

    # Not timed: generator execution time + the generated files, to check that every pair was generated.
    $generatedDir = Join-Path $rawDir "$name.generated"
    if (Test-Path $generatedDir) { Remove-Item -Recurse -Force $generatedDir }
    $analyzer = Invoke-Build $project @('-v:d', '-p:ReportAnalyzer=true', '-p:EmitCompilerGeneratedFiles=true', "-p:CompilerGeneratedFilesOutputPath=$generatedDir")
    Set-Content -Path (Join-Path $rawDir "$name.reportanalyzer.log") -Value ($analyzer.Output -join "`n") -Encoding utf8NoBOM
    $generators = @(Get-GeneratorTimes $analyzer.Output)
    $generatorKey = switch ($lib) { 'IronMapper' { 'IronMapper.Generator' } 'Mapperly' { 'Riok.Mapperly' } default { $null } }
    $own = $generators | Where-Object Name -eq $generatorKey | Select-Object -First 1
    $ownSeconds = if ($own) { $own.Seconds } else { $null }
    $allGeneratorsS = if ($generators.Count) { ($generators | Measure-Object -Property Seconds -Sum).Sum } else { $null }

    $sorted = [double[]] ($times | Sort-Object)
    $mean = ($sorted | Measure-Object -Average).Average
    $stdDev = [math]::Sqrt((($sorted | ForEach-Object { ($_ - $mean) * ($_ - $mean) }) | Measure-Object -Sum).Sum / [math]::Max(1, $sorted.Count - 1))
    [pscustomobject][ordered]@{
        N                 = $n
        Library           = $lib
        Runs              = $sorted.Count
        MedianS           = ConvertTo-InvariantNumber (Get-Percentile $sorted 0.5)
        MinS              = ConvertTo-InvariantNumber $sorted[0]
        MaxS              = ConvertTo-InvariantNumber $sorted[-1]
        MeanS             = ConvertTo-InvariantNumber $mean
        StdDevS           = ConvertTo-InvariantNumber $stdDev
        GeneratorS        = ($null -eq $ownSeconds) ? '' : (ConvertTo-InvariantNumber $ownSeconds)
        AllGeneratorsS    = ($null -eq $allGeneratorsS) ? '' : (ConvertTo-InvariantNumber $allGeneratorsS)
        GeneratedMappings = "$(Get-GeneratedMappingCount $lib $generatedDir)"
        Warnings          = $warnings.Count
        Timer             = $useHyperfine ? 'hyperfine' : 'stopwatch'
        WarmupRuns        = $WarmupRuns
        Date              = Get-UtcStamp
    }
}

