function Format-Duration($ns) {
    if ($null -eq $ns) { return '–' }
    $c = [cultureinfo]::InvariantCulture
    if ($ns -lt 1e3) { return $ns.ToString('N1', $c) + ' ns' }
    if ($ns -lt 1e6) { return ($ns / 1e3).ToString('N2', $c) + ' µs' }
    if ($ns -lt 1e9) { return ($ns / 1e6).ToString('N2', $c) + ' ms' }
    ($ns / 1e9).ToString('N2', $c) + ' s'
}

function Format-Ratio($value, $baseline) {
    if ($null -eq $value -or $null -eq $baseline -or $baseline -eq 0) { return '' }
    ' (×' + ($value / $baseline).ToString('N2', [cultureinfo]::InvariantCulture) + ')'
}

# Mermaid xychart-beta bar chart.
function New-BarChart([string] $title, [string] $yLabel, [string[]] $labels, [double[]] $values) {
    $c = [cultureinfo]::InvariantCulture
    $x = ($labels | ForEach-Object { "`"$_`"" }) -join ', '
    $y = ($values | ForEach-Object { $_.ToString('0.###', $c) }) -join ', '
    $max = ($values | Measure-Object -Maximum).Maximum
    $top = if ($max -gt 0) { [math]::Ceiling($max * 1.1) } else { 1 }
    @"
``````mermaid
xychart-beta
    title "$title"
    x-axis [$x]
    y-axis "$yLabel" 0 --> $top
    bar [$y]
``````
"@
}

