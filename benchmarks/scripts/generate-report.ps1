$sb = [System.Text.StringBuilder]::new()
function Add([string] $text = '') { [void] $sb.AppendLine($text) }

Add '# Mapper comparison: results'
Add
Add '> Generated by `scripts/generate-report.ps1` from the outputs of `scripts/run-all.ps1`. Do not edit by hand.'
Add '> Methodology and how to read the numbers: [README.md](../README.md).'
Add
if ($runInfo -and $runInfo.Mode -eq 'Quick') {
    Add '> [!WARNING]'
    Add '> **Quick run** (`run-all.ps1 -Quick`): `--job short`, fewer runs and smaller sizes. It only checks that everything works; the numbers are not comparable with a full run and must not be published.'
    Add
}

Add '## Environment'
Add
$bdnHost = Get-BdnHost
$commit = (& git -C (Get-BenchmarksDir) rev-parse --short HEAD 2>$null)
$dirty = (& git -C (Get-BenchmarksDir) status --porcelain -- . 2>$null)
$commitText = if ($commit) { "``$commit``$($dirty ? ' + uncommitted changes in `benchmarks/`' : '')" } else { 'unknown' }
Add '| | |'
Add '|---|---|'
Add "| Machine | $(Get-MachineSummary) |"
if ($bdnHost) { Add "| BenchmarkDotNet | $($bdnHost.BenchmarkDotNetVersion) · $($bdnHost.OsVersion) · $($bdnHost.RuntimeVersion) · $($bdnHost.Architecture) |" }
Add "| Report generated | $(Get-UtcStamp) |"
Add "| Commit | $commitText |"
if ($runInfo) {
    $steps = ($runInfo.Steps | ForEach-Object { "$($_.Name) $([timespan]::FromSeconds([double] $_.Seconds).ToString('h\:mm\:ss'))" }) -join ' · '
    $remeasured = @(Get-RemeasuredInputs $runInfo)
    $remeasuredText = if ($remeasured.Count) {
        '; re-measured separately after it (time the measurement finished): ' +
            (($remeasured | ForEach-Object { "$($_.Name) $($_.Time.ToString('yyyy-MM-dd HH:mm', [cultureinfo]::InvariantCulture)) UTC" }) -join ' · ')
    } else { '' }
    Add "| Run | $($runInfo.Mode), started $($runInfo.Started), total $([timespan]::FromSeconds([double] $runInfo.TotalSeconds).ToString('h\:mm\:ss')) ($steps)$remeasuredText |"
}
else { Add '| Run | results/raw/run-info.json not found: the scripts were run one by one, not through `run-all.ps1` |' }
Add
Add '| Package | Version | Role |'
Add '|---|---|---|'
foreach ($p in Get-PackageVersions) { Add "| $($p.Id) | $($p.Version) | $($p.Label) |" }
Add

Add '## Summary'
Add
Add ('One row per library. Times are BenchmarkDotNet means with the ratio to `Manual` in parentheses (hand-written code, the baseline). ' +
    "Collection and Allocated are for 100 000 orders. Cold start is the median process start + one mapping, framework-dependent, minus the Baseline console (no mapper). " +
    "NativeAOT: the executable runs and prints the correct checksum. Δ sizes are against the Baseline console. Δ build is the median build time with N = $buildN entity/DTO pairs minus the same project without a mapper. " +
    'Sizes in decimal units (1 KB = 1,000 bytes, 1 MB = 1,000,000 bytes). Details and caveats are in the sections below and in the README.')
Add
Add '| Library | Flat | Nested | Collection (100k) | Allocated (100k) | Cold start, Δ ms | NativeAOT | Δ publish (JIT) | Δ executable (AOT) | Δ build, s |'
Add '|---|---:|---:|---:|---:|---:|---|---:|---:|---:|'
$flatBase = Find-Result $bdn.Flat 'Manual'
$nestedBase = Find-Result $bdn.Nested 'Manual'
$collBase = Find-Result $bdn.Collection 'Manual' 'Count=100000'
foreach ($lib in $libraries) {
    $flat = Find-Result $bdn.Flat $lib
    $nested = Find-Result $bdn.Nested $lib
    $coll = Find-Result $bdn.Collection $lib 'Count=100000'
    $flatText = if ($flat) { (Format-Duration $flat.MeanNs) + (Format-Ratio $flat.MeanNs $flatBase.MeanNs) } else { '–' }
    $nestedText = if ($nested) { (Format-Duration $nested.MeanNs) + (Format-Ratio $nested.MeanNs $nestedBase.MeanNs) } else { '–' }
    $collText = if ($coll) { (Format-Duration $coll.MeanNs) + (Format-Ratio $coll.MeanNs $collBase.MeanNs) } else { '–' }
    $allocText = if ($coll -and $null -ne $coll.AllocatedBytes) { (Format-Size $coll.AllocatedBytes) + (Format-Ratio $coll.AllocatedBytes $collBase.AllocatedBytes) } else { '–' }

    $jit = $startupJit | Where-Object Probe -eq $lib | Select-Object -First 1
    $coldText = if ($jit -and $jit.Status -eq 'ok' -and $jitBaseline) { Format-Ms ([double] $jit.MedianMs - [double] $jitBaseline.MedianMs) } else { '–' }

    $aot = $startupAot | Where-Object Probe -eq $lib | Select-Object -First 1
    $aotText = if (-not $aot) { '–' }
    elseif ($aot.Status -eq 'ok' -and $aotBaseline -and $aot.Checksum -eq $aotBaseline.Checksum) { 'yes' }
    elseif ($aot.Status -eq 'publish failed') { 'publish failed' }
    else { 'no' }

    $jitSize = Get-PublishSize 'Jit' $lib
    $aotSize = Get-PublishSize 'Aot' $lib
    $jitDelta = if ($null -ne $jitSize -and $null -ne $jitBaseSize) { Format-SignedSize ($jitSize - $jitBaseSize) } else { '–' }
    $aotDelta = if ($null -ne $aotSize -and $null -ne $aotBaseSize) { Format-SignedSize ($aotSize - $aotBaseSize) } else { '–' }

    $build = $buildTime | Where-Object { [int] $_.N -eq $buildN -and $_.Library -eq $lib } | Select-Object -First 1
    $buildText = if ($build -and $buildBaseline) { Format-SignedSeconds ([double] $build.MedianS - [double] $buildBaseline.MedianS) } else { '–' }

    Add "| $lib | $flatText | $nestedText | $collText | $allocText | $coldText | $aotText | $jitDelta | $aotDelta | $buildText |"
}
Add
Add ('`IronMapper_IMapper` uses the same generator as `IronMapper`, so its build time is not measured separately. ' +
    '`IronMapper_StaticFormat` exists only in CustomConfig (a workaround, see the README).')
Add

Add '## Charts'
Add
$collLibs = @($libraries | Where-Object { Find-Result $bdn.Collection $_ 'Count=1000' })
foreach ($count in 10, 1000, 100000) {
    $values = foreach ($lib in $collLibs) {
        $r = Find-Result $bdn.Collection $lib "Count=$count"
        if ($r) { $r.MeanNs / $count } else { 0 }
    }
    if ($collLibs.Count) {
        $countText = $count.ToString('N0', [cultureinfo]::InvariantCulture)
        Add (New-BarChart "Collection, $countText orders: ns per order (lower is better)" 'ns/item' $collLibs ([double[]] $values))
        Add
    }
}
$coldLibs = @($libraries | Where-Object { $p = $_; $startupJit | Where-Object { $_.Probe -eq $p -and $_.Status -eq 'ok' } })
if ($coldLibs.Count -and $jitBaseline) {
    $values = foreach ($lib in $coldLibs) { [double] ($startupJit | Where-Object Probe -eq $lib).MedianMs - [double] $jitBaseline.MedianMs }
    Add (New-BarChart 'Cold start (process start + one mapping, JIT): Δ ms vs empty console' 'ms' $coldLibs ([double[]] ($values | ForEach-Object { [math]::Max(0, $_) })))
    Add
}
$coldBdn = @(Get-BdnResults 'Startup')
if ($coldBdn.Count) {
    $labels = @($libraries | Where-Object { Find-Result $coldBdn $_ })
    $values = foreach ($lib in $labels) { (Find-Result $coldBdn $lib).MeanNs / 1e6 }
    Add (New-BarChart 'In-process cold start (configuration + first mapping): ms' 'ms' $labels ([double[]] $values))
    Add
}
if (-not $collLibs.Count -and -not $coldLibs.Count) { Add '_No data for the charts yet._'; Add }

Add '## Runtime benchmarks'
Add
Add 'Full BenchmarkDotNet tables (`[MemoryDiagnoser]`, ratio to `Manual`). Artifacts in all formats (Markdown, CSV, HTML, JSON): `results/raw/bdn/results/` (not committed).'
Add
foreach ($s in $scenarios.Keys) {
    Add "### $s"
    Add
    Add $scenarios[$s]
    Add
    $md = Join-Path $bdnDir "Comparison.Benchmarks.${s}Benchmark-report-github.md"
    if (Test-Path $md) { Add ((Get-Content $md -Raw).Trim()) } else { Add '_Not measured._' }
    Add
}

