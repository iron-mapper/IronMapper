# Benchmarks of one class from the BenchmarkDotNet JSON report: Method, Parameters, MeanNs, AllocatedBytes.
function Get-BdnResults([string] $class) {
    $path = Join-Path $bdnDir "Comparison.Benchmarks.${class}Benchmark-report-full.json"
    if (-not (Test-Path $path)) { return @() }
    $json = Get-Content $path -Raw | ConvertFrom-Json
    foreach ($b in $json.Benchmarks) {
        $alloc = if ($b.PSObject.Properties['Memory'] -and $b.Memory) { [double] $b.Memory.BytesAllocatedPerOperation } else { $null }
        $mean = if ($b.Statistics) { [double] $b.Statistics.Mean } else { $null }
        [pscustomobject]@{ Method = $b.Method; Parameters = "$($b.Parameters)"; MeanNs = $mean; AllocatedBytes = $alloc }
    }
}

function Get-BdnHost {
    $file = Get-ChildItem -Path $bdnDir -Filter '*-report-full.json' -ErrorAction SilentlyContinue | Select-Object -First 1
    if (-not $file) { return $null }
    (Get-Content $file.FullName -Raw | ConvertFrom-Json).HostEnvironmentInfo
}

function Find-Result($results, [string] $method, [string] $parameters = '') {
    $results | Where-Object { $_.Method -eq $method -and $_.Parameters -eq $parameters } | Select-Object -First 1
}

function Import-CsvIfExists([string] $path) { if (Test-Path $path) { @(Import-Csv $path) } else { @() } }

# Body of a generated report for embedding: without its H1 and "Generated by" line, headings one level deeper.
function Get-EmbeddedReport([string] $name) {
    $path = Join-Path $resultsDir $name
    if (-not (Test-Path $path)) { return "_Not measured: ``results/$name`` does not exist._`n" }
    $inFence = $false
    $out = foreach ($line in (Get-Content $path)) {
        if ($line -match '^```') { $inFence = -not $inFence; $line; continue }
        if (-not $inFence) {
            if ($line -match '^# ') { continue }
            if ($line -match '^> Generated by') { continue }
            if ($line -match '^#{2,5} ') { $line = "#$line" }
        }
        $line
    }
    (($out -join "`n").Trim()) + "`n"
}

# ---------------------------------------------------------------------------------------------------------------------
# Formatting
# ---------------------------------------------------------------------------------------------------------------------

function Format-Duration($ns) {
    if ($null -eq $ns) { return '–' }
    $c = [cultureinfo]::InvariantCulture
    if ($ns -lt 1e3) { return $ns.ToString('N1', $c) + ' ns' }
    if ($ns -lt 1e6) { return ($ns / 1e3).ToString('N2', $c) + ' µs' }
    if ($ns -lt 1e9) { return ($ns / 1e6).ToString('N2', $c) + ' ms' }
    ($ns / 1e9).ToString('N2', $c) + ' s'
}

function Format-Ratio($value, $baseline) {
    if ($null -eq $value -or $null -eq $baseline -or $baseline -eq 0) { return '' }
    ' (×' + ($value / $baseline).ToString('N2', [cultureinfo]::InvariantCulture) + ')'
}

# Mermaid xychart-beta bar chart.
function New-BarChart([string] $title, [string] $yLabel, [string[]] $labels, [double[]] $values) {
    $c = [cultureinfo]::InvariantCulture
    $x = ($labels | ForEach-Object { "`"$_`"" }) -join ', '
    $y = ($values | ForEach-Object { $_.ToString('0.###', $c) }) -join ', '
    $max = ($values | Measure-Object -Maximum).Maximum
    $top = if ($max -gt 0) { [math]::Ceiling($max * 1.1) } else { 1 }
    @"
``````mermaid
xychart-beta
    title "$title"
    x-axis [$x]
    y-axis "$yLabel" 0 --> $top
    bar [$y]
``````
"@
}

