#Requires -Version 7.0
<#
.SYNOPSIS
    Builds results/RESULTS.md (BENCHMARK_SPEC.md, 12) from the outputs of the other scripts. Measures nothing.

.DESCRIPTION
    Sections:
      1. Environment: machine, OS, .NET SDK/runtime, BenchmarkDotNet, versions of all packages
         (Directory.Packages.props), date, commit, run mode (results/raw/run-info.json from run-all.ps1) and the
         scenarios measured again after the full run (measurement files written after its end).
      2. One-page summary: one row per library.
      3. Charts (Mermaid xychart-beta): Collection by size, cold start.
      4. Full BenchmarkDotNet tables of every runtime scenario (results/raw/bdn/results/*-report-github.md).
      5. Feature matrix, cold start, NativeAOT, size, build time (results/*.md, embedded).

    Missing inputs are reported in the document as "not measured", so the report can be built after a partial run.

.EXAMPLE
    pwsh ./scripts/generate-report.ps1
#>
[CmdletBinding()]
param()

$ErrorActionPreference = 'Stop'
Set-StrictMode -Version Latest
Import-Module (Join-Path $PSScriptRoot 'BenchmarkCommon.psm1') -Force

$resultsDir = Get-ResultsDir
$bdnDir = Join-Path (Get-ResultsRawDir) 'bdn' 'results'
$reportPath = Join-Path $resultsDir 'RESULTS.md'
$libraries = @('Manual', 'IronMapper', 'IronMapper_IMapper', 'Mapperly', 'Mapster', 'AutoMapper')
$scenarios = [ordered]@{
    Flat         = 'One flat object, ~15 properties (`UserEntity` → `UserDto`).'
    Nested       = 'One order with a customer, an address and 5–20 order lines with products.'
    Collection   = '`List<OrderEntity>` → `List<OrderDto>`; `ns/item` and `B/item` divide by `Count`.'
    CustomConfig = 'Rename, ignore, converter (`decimal` → `"F2"` string), computed property.'
    InPlace      = 'Update an existing `UserDto`.'
    DiOverhead   = 'Generated extension method vs `IMapper` from dependency injection, flat and nested.'
}

